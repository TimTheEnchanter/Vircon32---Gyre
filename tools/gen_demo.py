"""Usage: HEADLESS=./headless BIOS=StandardBios.v32 ROM=Gyre.v32 python3 gen_demo.py [games]

ROM should be a build without a built-in demo (so every bot game is saved),
and may start live games on a later level: the demo remembers its level.

Plays several scripted games in the headless emulator and turns the
best recording (as saved on the memory card) into demo_builtin.h."""
import random, struct, subprocess, os, sys
H=os.environ.get('HEADLESS','./headless'); BIOS=os.environ.get('BIOS','StandardBios.v32')
REC_WORDS=720
END=14000

def script(seed):
    # fire held almost all the time; the claw sweeps around the rim by
    # cycling the pressed direction, with random pauses and reversals
    r=random.Random(seed); L=[(460,464,4)]; f=520
    order=[1,3,0,2]; k=r.randint(0,3); step=r.choice([1,-1])
    while f<END-300:
        n=r.randint(60,160)
        L.append((f,f+n-3,6))                                   # hold fire
        g=f
        while g<f+n:
            d=r.randint(6,20)
            if r.random()<0.75: L.append((g,g+d,order[k%4]))
            if r.random()<0.3: k+=step
            if r.random()<0.05: step=-step
            g+=d+r.randint(0,12)
        if r.random()<0.04: L.append((f+10,f+13,7))           # superzapper
        f+=n
    for j in range(3): L.append((END-280+j*20,END-276+j*20,6))   # initials
    return '\n'.join('%d %d %d'%x for x in L)

def read_card(path):
    d=open(path,'rb').read()
    w=lambda i: struct.unpack('<i',d[8+4*i:12+4*i])[0]
    return dict(seed=w(31),frames=w(32),score=w(33),level=max(1,(w(38)>>8)&255),data=[w(40+i) for i in range(REC_WORDS)])

best=None
for k in range(int(sys.argv[1]) if len(sys.argv)>1 else 6):
    open('gen.txt','w').write(script(k))
    if os.path.exists('gen.card'): os.remove('gen.card')
    os.makedirs('genf',exist_ok=True)
    env=dict(os.environ,MEMCARD='gen.card',INPUT_SCRIPT='gen.txt',FRAME_FROM='999999')
    subprocess.run([H,BIOS,os.environ.get('ROM','Gyre.v32'),'genf',str(END+200),'1000'],env=env,capture_output=True)
    if not os.path.exists('gen.card'): print('script',k,'no card'); continue
    c=read_card('gen.card')
    print('script',k,'score',c['score'],'frames',c['frames'],'start level',c['level'])
    if c['frames']>0 and (best is None or c['score']>best['score']): best=c

rows=',\n    '.join(', '.join('0x%08X'%(v&0xFFFFFFFF) for v in best['data'][i:i+8]) for i in range(0,REC_WORDS,8))
open(os.environ.get('OUT','demo_builtin.h'),'w').write(f'''// generated by gen_demo.py: the recording shown in attract mode
// until a player sets a better game (score {best['score']}, {best['frames']} frames,
// starting on level {best['level']})
int builtin_demo_seed = {best['seed']};
int builtin_demo_frames = {best['frames']};
int builtin_demo_level = {best['level']};
int builtin_demo_score = {best['score']};
int[ REC_WORDS ] builtin_demo_data =
{{
    {rows}
}};
''')
print('chosen: score',best['score'],'frames',best['frames'],'seed',best['seed'])
